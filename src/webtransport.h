enum wt_status_t wt_server_accept(struct wt_server_t *server, uint64_t op_id);

/**
 * Reloads the TLS/transport configuration, optionally rebinding the socket.
 *
 * Completion: `WT_OP_SERVER_RELOADED`.
 */
enum wt_status_t wt_server_reload_config(struct wt_server_t *server,
                                         const struct wt_server_config_t *config,
                                         int32_t rebind,
                                         uint64_t op_id);

/**
 * Closes all connections and stops accepting.
 *
 * Completion: `WT_OP_SERVER_CLOSED`.
 */
enum wt_status_t wt_server_close(struct wt_server_t *server,
                                 uint32_t error_code,
                                 const uint8_t *reason,
                                 size_t reason_len,
                                 uint64_t op_id);

