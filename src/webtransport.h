/*
 * webtransport.h
 *
 * C ABI for `wtransport` (WebTransport over HTTP/3 over QUIC).
 *
 * Execution model
 * ---------------
 * The library owns one multi-threaded tokio runtime. Every function below is
 * safe to call from any thread and never blocks on network I/O:
 *
 *   - synchronous accessors read handle state and return immediately;
 *   - asynchronous operations are enqueued onto the runtime and return `WT_OK`
 *     (or an immediate error such as `WT_ERR_OP_BUSY`), reporting their outcome
 *     later through the event callback registered with `wt_runtime_init`;
 *   - the event callback runs on a tokio worker thread and is never invoked
 *     concurrently, so no locking is needed on the receiving side.
 *
 * Because the Dart binding uses `NativeCallable.listener` (an asynchronous
 * callback: the native call only transports the pointer), every completion is
 * delivered as an owned `wt_event_batch_t` which the callee must release with
 * `wt_batch_free`.
 *
 * Handles
 * -------
 * `wt_*_t` pointers are reference counted. Releasing a handle while operations
 * referring to it are still in flight is safe. Handles delivered inside a
 * `wt_event_t` are owned by the callee and must be released with the matching
 * `wt_*_free`.
 *
 * Performance notes
 * -----------------
 *   - completions are coalesced into batches to cut the number of isolate
 *     messages;
 *   - `wt_recv_stream_read` can read directly into caller supplied memory
 *     (`wt_buffer_t`), giving a zero-copy receive path into Dart;
 *   - received datagrams are delivered from the QUIC receive buffer without an
 *     intermediate copy;
 *   - each stream allows one outstanding operation, enforced by
 *     `WT_ERR_OP_BUSY`, which keeps ordering deterministic and lock free.
 */

